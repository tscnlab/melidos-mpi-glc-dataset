#!/usr/bin/env python3
"""Encode published R-factor levels as one-based positions.

The participant CSVs must first be regenerated by
split_imported_by_participant.R, which writes R factors as integer positions.
Numeric device-code variables whose labels begin with ``Code `` are preserved.
"""

import argparse
import json
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("datasets_json", type=Path)
    args = parser.parse_args()

    records = json.loads(args.datasets_json.read_text(encoding="utf-8"))
    updated = 0
    preserved_device_codes = 0

    for dataset in records:
        for group in dataset.get("dataset_file", []):
            for variable in group.get("dataset_file_variables", []):
                if variable.get("dataset_file_variables_type") != "factor":
                    continue
                levels = variable.get("dataset_file_variables_factor_levels", [])
                if not levels:
                    raise ValueError(
                        "Factor has no levels: "
                        f"{dataset.get('dataset_internal_id')}."
                        f"{variable.get('dataset_file_variables_name')}"
                    )
                if all(
                    level.get("label") == f"Code {level.get('value')}"
                    for level in levels
                ):
                    preserved_device_codes += 1
                    continue
                for index, level in enumerate(levels, start=1):
                    level["value"] = str(index)
                updated += 1

    args.datasets_json.write_text(
        json.dumps(records, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"Encoded {updated} factor definitions as one-based positions.")
    print(f"Preserved {preserved_device_codes} numeric device-code definitions.")


if __name__ == "__main__":
    main()
